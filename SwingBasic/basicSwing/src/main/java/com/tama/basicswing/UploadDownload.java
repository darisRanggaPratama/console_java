    private void processExcelFile(File file) {
        try (FileInputStream fis = new FileInputStream(file); XSSFWorkbook workbook = new XSSFWorkbook(fis)) {

            XSSFSheet sheet = workbook.getSheetAt(0);
            Connection conn = getConnection();

            String sql = "INSERT INTO Customer (id, name, email, birth) VALUES (?, ?, ?, ?)";
            PreparedStatement pstmt = conn.prepareStatement(sql);

            for (Row row : sheet) {
                if (row.getRowNum() == 0) {
                    continue; // Skip header row
                }
                Cell idCell = row.getCell(0);
                Cell nameCell = row.getCell(1);
                Cell emailCell = row.getCell(2);
                Cell birthCell = row.getCell(3);

                pstmt.setString(1, idCell.getStringCellValue());
                pstmt.setString(2, nameCell.getStringCellValue());
                pstmt.setString(3, emailCell.getStringCellValue());
                pstmt.setDate(4, new java.sql.Date(birthCell.getDateCellValue().getTime()));

                pstmt.executeUpdate();
            }

            pstmt.close();
            conn.close();

            JOptionPane.showMessageDialog(this, "Data berhasil di-upload ke database.", "Sukses", JOptionPane.INFORMATION_MESSAGE);

        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }

